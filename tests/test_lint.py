import json

import pytest

import agentsmd_lint as al

PATHS = {"src/app.py", "src/util/log.py", "docs/guide.md", "package.json", "Makefile", "README.md"}
SCRIPTS = json.dumps({"scripts": {"test": "x", "lint:fix": "y"}})


def read(path):
    return {
        "package.json": SCRIPTS,
        "Makefile": "test:\n\tpytest\nlint fmt:\n\truff\nX := 1\n",
    }.get(path)


def rules(text, readme=None):
    return {f["rule"] for f in al.lint(text, PATHS, read, readme)["findings"]}


def test_live_paths_are_clean():
    assert "dead-path" not in rules("See `src/app.py`, `docs/guide.md:12`, `./src/util/log.py`.")


def test_path_relative_to_a_subdirectory_counts():
    assert "dead-path" not in rules("See `util/log.py`.")


def test_dead_path_is_reported():
    findings = al.lint("Edit `src/old.py`.", PATHS, read)["findings"]
    assert findings[0]["rule"] == "dead-path" and "src/old.py" in findings[0]["message"]


def test_non_paths_are_ignored():
    text = "Use `https://x.io/a.py`, `@scope/pkg.js`, `application/json`, `<name>.py`, `--flag.py`."
    assert "dead-path" not in rules(text)


@pytest.mark.parametrize(
    "token",
    [
        ".js",
        "posting.md",
        "src/generated/dist/app.js",
        "src/YourIcon.tsx",
        "src/foo/bar.py",
        "other-repo/src/app.py",
        "vercel/next.js",
    ],
)
def test_ambiguous_tokens_stay_silent(token):
    assert "dead-path" not in rules(f"See `{token}`.")


def test_gitignored_paths_are_not_dead():
    reader = lambda p: "/secrets/\n*.log\n" if p == ".gitignore" else read(p)  # noqa: E731
    found = {
        f["rule"]
        for f in al.lint("See `src/secrets/key.txt` and `src/trace.log`.", PATHS, reader)[
            "findings"
        ]
    }
    assert "dead-path" not in found


def test_fragments_and_symbols_are_stripped():
    assert "dead-path" not in rules("See `docs/guide.md#install` and `src/app.py::main`.")


def test_extensionless_doc_links_resolve():
    assert "dead-path" not in rules("See `docs/guide`.")


@pytest.mark.parametrize(
    "line",
    [
        "`src/old` was removed, do not restore it.",
        "Check that `src/hooks/x` exists.",
        "`src/gen/api.ts` is generated by CI.",
    ],
)
def test_hedged_lines_make_no_claim(line):
    assert "dead-path" not in rules(line)


def test_hedge_word_inside_a_path_is_still_checked():
    assert "dead-path" in rules("See `src/legacy/gone.py`.")


def test_placeholder_module_name_is_ignored():
    assert "dead-path" not in rules("OSS module exports its `src/X` companion.")


@pytest.mark.parametrize(
    "command", ["pnpm run -C scripts x", "bun run --cwd pkg test", "bun run src/a.ts"]
)
def test_flags_and_files_are_not_scripts(command):
    assert "unknown-script" not in rules(f"Run `{command}`.")


def test_prose_is_not_a_make_command():
    assert "unknown-make-target" not in rules("Please make sure the tests pass.")


def test_fenced_make_command_is_checked():
    assert "unknown-make-target" in rules("```\nmake deploy\n```")


def test_unknown_top_level_without_extension_is_ignored():
    assert "dead-path" not in rules("Import from `react/jsx-runtime`.")


def test_known_top_level_without_extension_is_checked():
    assert "dead-path" in rules("Look in `src/missing`.")


def test_npm_scripts():
    assert "unknown-script" not in rules("Run `npm run lint:fix`.")
    assert "unknown-script" in rules("Run `npm run deploy`.")


def test_make_targets_including_multiple_targets_on_a_rule():
    assert "unknown-make-target" not in rules("Run `make fmt`.")
    assert "unknown-make-target" in rules("Run `make deploy`.")


def test_makefile_with_include_is_not_judged():
    reader = lambda p: "include common.mk\n" if p == "Makefile" else read(p)  # noqa: E731
    found = {f["rule"] for f in al.lint("Run `make deploy`.", PATHS, reader)["findings"]}
    assert "unknown-make-target" not in found


def test_overview_detection():
    assert "repo-overview" in rules("## Project structure\n\ntext")
    assert "repo-overview" in rules("```\n├── src\n```")
    assert "repo-overview" not in rules("## Testing\n\nrun `pytest`")


def test_vague_ignores_code_fences():
    assert "vague-instruction" in rules("Always follow best practices.")
    assert "vague-instruction" not in rules("```\n# best practices\n```")


def test_readme_overlap():
    shared = " ".join(f"word{i}" for i in range(40))
    assert "readme-overlap" in rules(shared, readme=shared)
    assert "readme-overlap" not in rules(shared, readme="something else entirely")


def test_missing_verify_command():
    assert "no-verify-command" in rules("Be nice.")
    assert "no-verify-command" not in rules("Run `pytest -q`.")


def test_size_limit():
    assert "size" in rules("x\n" * 250)
    assert "size" not in rules("x\n" * 50)


def test_cli_exit_codes(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.py").write_text("")
    (tmp_path / "AGENTS.md").write_text("Edit `src/gone.py`.\n")
    assert al.main([str(tmp_path)]) == 0
    assert al.main([str(tmp_path), "--strict"]) == 1
    (tmp_path / "AGENTS.md").write_text("Run `pytest`.\n")
    assert al.main([str(tmp_path)]) == 0
    (tmp_path / "AGENTS.md").unlink()
    assert al.main([str(tmp_path)]) == 2
